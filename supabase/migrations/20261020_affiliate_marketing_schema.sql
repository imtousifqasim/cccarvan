-- Enable UUID extension if not already present
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ------------------------------------------------------------------------------
-- 1. AFFILIATES TABLE
-- Stores affiliate accounts, approval status, referral codes & custom commission rates
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.affiliates (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL DEFAULT uuid_generate_v4() UNIQUE,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT,
    password_hash TEXT NOT NULL,
    promo_details TEXT,
    website_or_social TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'suspended')),
    referral_code TEXT UNIQUE,                     -- Generated upon admin approval
    commission_rate NUMERIC(5, 2),                 -- NULL = fallback to global default
    rejection_reason TEXT,
    approved_at TIMESTAMPTZ,
    approved_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_affiliates_email ON public.affiliates (email);
CREATE INDEX IF NOT EXISTS idx_affiliates_status ON public.affiliates (status);
CREATE INDEX IF NOT EXISTS idx_affiliates_referral_code ON public.affiliates (referral_code);

-- ------------------------------------------------------------------------------
-- 2. AFFILIATE LINKS TABLE
-- Unique tracking slugs generated by affiliates pointing to products or categories
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.affiliate_links (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    affiliate_id UUID NOT NULL REFERENCES public.affiliates(id) ON DELETE CASCADE,
    product_id UUID REFERENCES public.products(id) ON DELETE SET NULL,
    category_id UUID REFERENCES public.categories(id) ON DELETE SET NULL,
    slug TEXT NOT NULL UNIQUE,                      -- E.g. "cc-a1b2c3d4"
    click_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_affiliate_links_affiliate_id ON public.affiliate_links (affiliate_id);
CREATE INDEX IF NOT EXISTS idx_affiliate_links_slug ON public.affiliate_links (slug);
CREATE INDEX IF NOT EXISTS idx_affiliate_links_product_id ON public.affiliate_links (product_id);
CREATE INDEX IF NOT EXISTS idx_affiliate_links_category_id ON public.affiliate_links (category_id);

-- ------------------------------------------------------------------------------
-- 3. ORDERS TABLE AFFILIATE COLUMNS
-- Attribution snapshot on order placement
-- ------------------------------------------------------------------------------
ALTER TABLE public.orders 
ADD COLUMN IF NOT EXISTS affiliate_id UUID REFERENCES public.affiliates(id) ON DELETE SET NULL;

ALTER TABLE public.orders 
ADD COLUMN IF NOT EXISTS affiliate_link_id UUID REFERENCES public.affiliate_links(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_orders_affiliate_id ON public.orders (affiliate_id);

-- ------------------------------------------------------------------------------
-- 4. COMMISSIONS TABLE
-- One row per sold item attributed to an affiliate with snapshot rate & sale amount
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.commissions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    affiliate_id UUID NOT NULL REFERENCES public.affiliates(id) ON DELETE CASCADE,
    affiliate_link_id UUID REFERENCES public.affiliate_links(id) ON DELETE SET NULL,
    order_id UUID NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    order_item_id UUID REFERENCES public.order_items(id) ON DELETE SET NULL,
    product_id UUID NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    sale_amount NUMERIC(12, 2) NOT NULL CHECK (sale_amount >= 0),
    commission_rate NUMERIC(5, 2) NOT NULL,        -- Snapshot rate at time of order
    commission_amount NUMERIC(12, 2) NOT NULL CHECK (commission_amount >= 0),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'reversed')),
    available_at TIMESTAMPTZ,                      -- When commission becomes withdrawable (after hold days)
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_commissions_affiliate_id ON public.commissions (affiliate_id);
CREATE INDEX IF NOT EXISTS idx_commissions_order_id ON public.commissions (order_id);
CREATE INDEX IF NOT EXISTS idx_commissions_status ON public.commissions (status);
CREATE INDEX IF NOT EXISTS idx_commissions_available_at ON public.commissions (available_at);

-- ------------------------------------------------------------------------------
-- 5. PAYOUT METHODS TABLE
-- Saved payout accounts (Easypaisa, JazzCash, Bank Transfer)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.payout_methods (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    affiliate_id UUID NOT NULL REFERENCES public.affiliates(id) ON DELETE CASCADE,
    method TEXT NOT NULL CHECK (method IN ('easypaisa', 'jazzcash', 'bank_transfer', 'other')),
    account_title TEXT NOT NULL,
    account_number TEXT NOT NULL,
    bank_name TEXT,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_payout_methods_affiliate_id ON public.payout_methods (affiliate_id);

-- ------------------------------------------------------------------------------
-- 6. WITHDRAWALS TABLE
-- Withdrawal requests with status lifecycle, admin notes, and transaction references
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.withdrawals (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    affiliate_id UUID NOT NULL REFERENCES public.affiliates(id) ON DELETE CASCADE,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    method TEXT NOT NULL,                          -- Snapshot of payout method
    account_title TEXT NOT NULL,
    account_number TEXT NOT NULL,
    bank_name TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'paid')),
    admin_note TEXT,
    transaction_reference TEXT,                    -- Payment tracking ID provided by admin
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMPTZ,
    processed_by TEXT
);

CREATE INDEX IF NOT EXISTS idx_withdrawals_affiliate_id ON public.withdrawals (affiliate_id);
CREATE INDEX IF NOT EXISTS idx_withdrawals_status ON public.withdrawals (status);
CREATE INDEX IF NOT EXISTS idx_withdrawals_requested_at ON public.withdrawals (requested_at);

-- ------------------------------------------------------------------------------
-- 7. GLOBAL AFFILIATE SETTINGS TABLE
-- Commission defaults, cookie attribution duration, hold window, and withdrawal thresholds
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.affiliate_settings (
    id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    default_commission_rate NUMERIC(5, 2) NOT NULL DEFAULT 10.00,
    cookie_days INTEGER NOT NULL DEFAULT 30,
    hold_days INTEGER NOT NULL DEFAULT 7,
    min_withdrawal NUMERIC(12, 2) NOT NULL DEFAULT 1000.00,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

